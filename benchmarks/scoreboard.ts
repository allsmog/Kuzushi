#!/usr/bin/env tsx

/**
 * Render a publishable detection-quality scoreboard from benchmark metrics.
 *
 * Reads one or more metrics JSON files (produced by `harness.ts --output`)
 * and writes a versioned Markdown scoreboard with artifact provenance. This is the artifact
 * that turns "Kuzushi finds real bugs" from a claim into a number anyone can
 * read and track across releases.
 *
 * Usage:
 *   tsx benchmarks/scoreboard.ts --results a.json,b.json
 *   tsx benchmarks/scoreboard.ts --results metrics.json --output benchmarks/SCOREBOARD.md
 */

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { parseArgs } from "node:util";
import { assertCompatibleResultSet, assertMetrics, shortDigest } from "./benchmark-provenance.js";
import type { BenchmarkMetrics } from "./types.js";

const { values: args } = parseArgs({
  options: {
    results: { type: "string" },
    output: { type: "string", default: "benchmarks/SCOREBOARD.md" },
    help: { type: "boolean", short: "h", default: false },
  },
  strict: true,
});

if (args.help || !args.results) {
  console.log(`
Kuzushi Benchmark Scoreboard

Usage:
  tsx benchmarks/scoreboard.ts --results <path,...> [--output <md>]

Options:
  --results <path,...>   Comma-separated metrics JSON files (from harness.ts --output)
  --output <path>        Scoreboard Markdown path (default: benchmarks/SCOREBOARD.md)
  -h, --help             Show this help
`);
  process.exit(args.help ? 0 : 1);
}

function loadMetrics(paths: string[]): BenchmarkMetrics[] {
  return paths.map((path) => {
    const resolved = resolve(path.trim());
    if (!existsSync(resolved)) {
      throw new Error(`metrics file not found: ${resolved}`);
    }
    const parsed: unknown = JSON.parse(readFileSync(resolved, "utf8"));
    assertMetrics(parsed, resolved);
    return parsed;
  });
}

function pct(value: number): string {
  return `${(value * 100).toFixed(1)}%`;
}

function totalsRow(metrics: BenchmarkMetrics[]): string {
  const sum = (key: "tp" | "fp" | "fn" | "tn") => metrics.reduce((acc, m) => acc + m[key], 0);
  const tp = sum("tp");
  const fp = sum("fp");
  const fn = sum("fn");
  const precision = tp + fp > 0 ? tp / (tp + fp) : 0;
  const recall = tp + fn > 0 ? tp / (tp + fn) : 0;
  const f1 = precision + recall > 0 ? (2 * precision * recall) / (precision + recall) : 0;
  const cost = checkedScoreboardCost(metrics);
  return row([
    "**All datasets**",
    "**compatible set**",
    `**${tp}**`,
    String(fp),
    String(fn),
    `**${pct(precision)}**`,
    `**${pct(recall)}**`,
    pct(f1),
    `$${cost.toFixed(4)}`,
  ]);
}

function checkedScoreboardCost(metrics: BenchmarkMetrics[]): number {
  let total = 0;
  for (const metric of metrics) {
    const cost = checkedCostOperand(metric.costUsd, metric.dataset);
    const next = total + cost;
    if (!Number.isFinite(next)) {
      throw new Error(`scoreboard aggregate cost overflowed while adding ${metric.dataset}`);
    }
    total = next;
  }
  return total;
}

function checkedCostOperand(cost: number, dataset: string): number {
  if (!Number.isFinite(cost) || cost < 0) {
    throw new Error(`scoreboard cost for ${dataset} must be finite and nonnegative`);
  }
  return cost;
}

function row(cells: string[]): string {
  return `| ${cells.join(" | ")} |`;
}

function datasetRow(m: BenchmarkMetrics): string {
  return row([
    m.dataset,
    m.provenance.comparable.datasetRevision,
    String(m.tp),
    String(m.fp),
    String(m.fn),
    pct(m.precision),
    pct(m.recall),
    pct(m.f1),
    `$${m.costUsd.toFixed(4)}`,
  ]);
}

function renderScoreboard(metrics: BenchmarkMetrics[]): string {
  const first = metrics[0].provenance;
  const header = [
    "Dataset",
    "Dataset revision",
    "TP",
    "FP",
    "FN",
    "Precision",
    "Recall",
    "F1",
    "Cost",
  ];
  const lines = [
    "# Kuzushi Detection Scoreboard",
    "",
    "<!-- Generated by benchmarks/scoreboard.ts — do not edit by hand. -->",
    "",
    `- Mode: \`${first.mode}\``,
    `- Model: \`${first.comparable.modelIdentity}\``,
    `- Harness: \`${first.comparable.harnessContractVersion}\` (\`${shortDigest(first.comparable.harnessDigest)}\`)`,
    `- Scan config: \`${shortDigest(first.comparable.scanConfigDigest)}\``,
    `- Scoring: \`${first.comparable.scoringMode}\``,
    `- Code revisions: ${observationValues(metrics, "kuzushiRevision")}`,
    `- Runtime config hashes: ${optionalObservationValues(metrics, "configHash")}`,
    `- Observed model calls: ${modelCallSummary(metrics)}`,
    `- Generated observations: ${observationValues(metrics, "generatedAt")}`,
    "",
    row(header),
    row(header.map(() => "---")),
    ...metrics.map(datasetRow),
    totalsRow(metrics),
    "",
  ];
  return `${lines.join("\n")}\n`;
}

function optionalObservationValues(metrics: BenchmarkMetrics[], key: "configHash"): string {
  const values = [...new Set(metrics.flatMap((metric) => metric.provenance.observed[key] ?? []))]
    .sort()
    .map((value) => `\`${value}\``);
  return values.length === 0 ? "`not recorded (synthetic fixture)`" : values.join(", ");
}

function modelCallSummary(metrics: BenchmarkMetrics[]): string {
  const calls = metrics.reduce((total, metric) => total + metric.spend.llmCallCount, 0);
  const models = [...new Set(metrics.flatMap((metric) => metric.spend.models))].sort();
  const audit = metrics.every((metric) => metric.spend.llmAuditComplete)
    ? "complete"
    : "incomplete";
  const modelText = models.length === 0 ? "none" : models.join(", ");
  return `\`${calls}\` (audit ${audit}; models: ${modelText})`;
}

function observationValues(
  metrics: BenchmarkMetrics[],
  key: "kuzushiRevision" | "generatedAt",
): string {
  const values = [...new Set(metrics.map((metric) => metric.provenance.observed[key]))].sort();
  return values.map((value) => `\`${value}\``).join(", ");
}

const metrics = loadMetrics((args.results ?? "").split(","));
assertCompatibleResultSet(metrics, "scoreboard results");
const outputPath = resolve(args.output ?? "benchmarks/SCOREBOARD.md");
writeFileSync(outputPath, renderScoreboard(metrics));
console.log(`Scoreboard written to: ${outputPath}`);
