#!/usr/bin/env tsx

/**
 * Render a publishable detection-quality scoreboard from benchmark metrics.
 *
 * Reads one or more metrics JSON files (produced by `harness.ts --output`)
 * and writes a versioned Markdown scoreboard with provenance (commit, date,
 * whether the run was mock-backed or a real LLM run). This is the artifact
 * that turns "Kuzushi finds real bugs" from a claim into a number anyone can
 * read and track across releases.
 *
 * Usage:
 *   tsx benchmarks/scoreboard.ts --results a.json,b.json
 *   tsx benchmarks/scoreboard.ts --results metrics.json --output benchmarks/SCOREBOARD.md --mock
 */

import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { parseArgs } from "node:util";
import type { BenchmarkMetrics } from "./types.js";

const { values: args } = parseArgs({
  options: {
    results: { type: "string" },
    output: { type: "string", default: "benchmarks/SCOREBOARD.md" },
    mock: { type: "boolean", default: false },
    help: { type: "boolean", short: "h", default: false },
  },
  strict: true,
});

if (args.help || !args.results) {
  console.log(`
Kuzushi Benchmark Scoreboard

Usage:
  tsx benchmarks/scoreboard.ts --results <path,...> [--output <md>] [--mock]

Options:
  --results <path,...>   Comma-separated metrics JSON files (from harness.ts --output)
  --output <path>        Scoreboard Markdown path (default: benchmarks/SCOREBOARD.md)
  --mock                 Mark the run as mock-backed (deterministic fixtures, not a real LLM)
  -h, --help             Show this help
`);
  process.exit(args.help ? 0 : 1);
}

function loadMetrics(paths: string[]): BenchmarkMetrics[] {
  return paths.map((path) => {
    const resolved = resolve(path.trim());
    if (!existsSync(resolved)) {
      throw new Error(`metrics file not found: ${resolved}`);
    }
    return JSON.parse(readFileSync(resolved, "utf8")) as BenchmarkMetrics;
  });
}

function gitCommit(): string {
  try {
    return execFileSync("git", ["rev-parse", "--short", "HEAD"], { encoding: "utf8" }).trim();
  } catch {
    return "unknown";
  }
}

function pct(value: number): string {
  return `${(value * 100).toFixed(1)}%`;
}

function totalsRow(metrics: BenchmarkMetrics[]): string {
  const sum = (key: "tp" | "fp" | "fn" | "tn") => metrics.reduce((acc, m) => acc + m[key], 0);
  const tp = sum("tp");
  const fp = sum("fp");
  const fn = sum("fn");
  const precision = tp + fp > 0 ? tp / (tp + fp) : 0;
  const recall = tp + fn > 0 ? tp / (tp + fn) : 0;
  const f1 = precision + recall > 0 ? (2 * precision * recall) / (precision + recall) : 0;
  const cost = metrics.reduce((acc, m) => acc + m.costUsd, 0);
  return row([
    "**All datasets**",
    `**${tp}**`,
    String(fp),
    String(fn),
    `**${pct(precision)}**`,
    `**${pct(recall)}**`,
    pct(f1),
    `$${cost.toFixed(4)}`,
  ]);
}

function row(cells: string[]): string {
  return `| ${cells.join(" | ")} |`;
}

function datasetRow(m: BenchmarkMetrics): string {
  return row([
    m.dataset,
    String(m.tp),
    String(m.fp),
    String(m.fn),
    pct(m.precision),
    pct(m.recall),
    pct(m.f1),
    `$${m.costUsd.toFixed(4)}`,
  ]);
}

function renderScoreboard(metrics: BenchmarkMetrics[], mock: boolean): string {
  const header = ["Dataset", "TP", "FP", "FN", "Precision", "Recall", "F1", "Cost"];
  const lines = [
    "# Kuzushi Detection Scoreboard",
    "",
    "<!-- Generated by benchmarks/scoreboard.ts — do not edit by hand. -->",
    "",
    `- Commit: \`${gitCommit()}\``,
    `- Generated: ${new Date().toISOString()}`,
    `- Mode: ${mock ? "**mock-backed** (deterministic fixtures, not a real LLM run)" : "real LLM run"}`,
    "",
    row(header),
    row(header.map(() => "---")),
    ...metrics.map(datasetRow),
    totalsRow(metrics),
    "",
  ];
  return `${lines.join("\n")}\n`;
}

const metrics = loadMetrics((args.results ?? "").split(","));
const outputPath = resolve(args.output ?? "benchmarks/SCOREBOARD.md");
writeFileSync(outputPath, renderScoreboard(metrics, args.mock ?? false));
console.log(`Scoreboard written to: ${outputPath}`);
