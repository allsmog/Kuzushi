/**
 * GitHub PR-comment integration.
 *
 * Turns a workspace's vulns into a single-comment summary posted to a PR.
 * Intentionally one comment per run — not N inline review comments — so
 * reviewers get a deterministic header/table rather than noise per line.
 *
 * Usage: `workspace:export github --pr owner/repo#123` pulls the workspace
 * vulns, renders markdown, and posts to /repos/{owner}/{repo}/issues/{pr}/comments
 * using $GITHUB_TOKEN from the environment. Dry-run mode just returns the
 * rendered body.
 */

import type { WorkspaceManager } from "../manager.js";

export interface PrRef {
  owner: string;
  repo: string;
  number: number;
}

/** Parse `owner/repo#123` → { owner, repo, number }. Returns null on malformed. */
export function parsePrRef(raw: string): PrRef | null {
  const m = /^([^/\s]+)\/([^#\s]+)#(\d+)$/.exec(raw.trim());
  if (!m) return null;
  const n = Number.parseInt(m[3] ?? "", 10);
  if (!Number.isFinite(n) || n <= 0) return null;
  return { owner: m[1] as string, repo: m[2] as string, number: n };
}

export interface RenderOptions {
  /** Grouping threshold — severities below this are folded into an "Other" section. */
  minSeverity?: "info" | "low" | "medium" | "high" | "critical";
  /** Max inline vulns per severity group. Default 25. */
  maxPerGroup?: number;
}

export function renderGitHubComment(
  ws: WorkspaceManager,
  workspaceId: string,
  opts: RenderOptions = {},
): string {
  const workspace = ws.get(workspaceId);
  if (!workspace) throw new Error(`Unknown workspace: ${workspaceId}`);

  const vulns = ws.vulns.listForWorkspace(workspaceId);
  const min = opts.minSeverity ?? "info";
  const minRank = SEVERITY_RANK[min];
  const visible = vulns.filter((v) => (SEVERITY_RANK[v.severity ?? "info"] ?? 0) >= minRank);
  const cap = opts.maxPerGroup ?? 25;

  const lines: string[] = [];
  lines.push(`## 🔐 Kuzushi scan — ${workspace.name}`);
  lines.push("");
  lines.push(renderSummary(visible));
  lines.push("");

  const order = ["critical", "high", "medium", "low", "info"] as const;
  for (const sev of order) {
    const bucket = visible.filter((v) => v.severity === sev);
    if (bucket.length === 0) continue;
    lines.push(`### ${sev.toUpperCase()} · ${bucket.length}`);
    lines.push("");
    lines.push("| Finding | References | Location |");
    lines.push("| ------- | ---------- | -------- |");
    const shown = bucket.slice(0, cap);
    for (const v of shown) {
      const refs =
        (v.references ?? [])
          .filter((r) => r.type === "CVE" || r.type === "CWE")
          .map((r) => `${r.type}:${r.value}`)
          .join(" ")
          .replace(/\|/g, "\\|") || "—";
      const loc = String((v.metadata as { location?: string } | undefined)?.location ?? "").replace(
        /\|/g,
        "\\|",
      );
      const name = v.name.replace(/\|/g, "\\|");
      lines.push(`| ${name} | ${refs} | ${loc} |`);
    }
    if (bucket.length > cap) {
      lines.push(`| _…and ${bucket.length - cap} more_ | | |`);
    }
    lines.push("");
  }

  lines.push("---");
  lines.push(`<sub>Generated by Kuzushi. Re-run \`workspace:export github\` to refresh.</sub>`);
  return lines.join("\n");
}

function renderSummary(visible: ReturnType<WorkspaceManager["vulns"]["listForWorkspace"]>): string {
  const counts = { critical: 0, high: 0, medium: 0, low: 0, info: 0 } as Record<string, number>;
  for (const v of visible) {
    const k = v.severity ?? "info";
    counts[k] = (counts[k] ?? 0) + 1;
  }
  const parts = Object.entries(counts)
    .filter(([, n]) => n > 0)
    .map(([sev, n]) => `**${sev}**: ${n}`);
  if (parts.length === 0) return "_No findings._";
  return parts.join(" · ");
}

const SEVERITY_RANK: Record<string, number> = {
  info: 0,
  low: 1,
  medium: 2,
  high: 3,
  critical: 4,
};

export interface PostOptions {
  /** Personal access token (defaults to env GITHUB_TOKEN). */
  token?: string;
  /** Dry run — skip the network call and return the rendered body. */
  dryRun?: boolean;
  /** Override the base URL for GitHub Enterprise instances. */
  apiBase?: string;
  /** Override fetch for tests. */
  fetchImpl?: typeof fetch;
}

export interface PostResult {
  posted: boolean;
  url?: string;
  body: string;
  warning?: string;
}

/**
 * POST the rendered body to /repos/{owner}/{repo}/issues/{number}/comments.
 * The API treats PRs as issues for this endpoint. Returns { posted, url, body }.
 */
export async function postPrComment(
  ref: PrRef,
  body: string,
  opts: PostOptions = {},
): Promise<PostResult> {
  if (opts.dryRun) return { posted: false, body, warning: "dry-run: no POST issued" };
  const token = opts.token ?? process.env.GITHUB_TOKEN;
  if (!token) {
    return { posted: false, body, warning: "GITHUB_TOKEN not set — skipped posting." };
  }
  const base = opts.apiBase ?? "https://api.github.com";
  const url = `${base}/repos/${ref.owner}/${ref.repo}/issues/${ref.number}/comments`;
  const fx = opts.fetchImpl ?? fetch;
  const res = await fx(url, {
    method: "POST",
    headers: {
      Accept: "application/vnd.github+json",
      Authorization: `Bearer ${token}`,
      "X-GitHub-Api-Version": "2022-11-28",
      "Content-Type": "application/json",
    },
    body: JSON.stringify({ body }),
  });
  if (!res.ok) {
    const text = await res.text().catch(() => "");
    return {
      posted: false,
      body,
      warning: `GitHub API ${res.status}: ${text.slice(0, 120)}`,
    };
  }
  const json = (await res.json().catch(() => ({}))) as { html_url?: string };
  return { posted: true, body, url: json.html_url };
}
