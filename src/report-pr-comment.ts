/**
 * Markdown PR comment generator — Phase B.5.
 *
 * Turns a `SummaryData` snapshot (optionally with a repo name + run URL)
 * into a short GitHub-flavoured markdown block operators can paste into a
 * PR review or pipe to `gh pr comment -F -`. Intentionally opinionated:
 * one header, one counts table, one findings table (top 10), one footer
 * with cost + duration. No embedded ANSI — this output is meant for
 * rendering in a browser.
 *
 * Usage:
 *
 *   const md = buildPrComment(summary, { repoName: "acme-api" });
 *   await fs.writeFile("comment.md", md);
 *
 *   # or pipe to gh:
 *   $ kuzushi comment --pr 123 | gh pr comment 123 -F -
 */

import type { ActionableFinding, SummaryData } from "./ui/state.js";

export interface PrCommentOptions {
  repoName?: string;
  /** Optional link to a run dashboard / artefact (rendered on the header line). */
  runUrl?: string;
  /** How many top findings to include. Default 10. */
  topN?: number;
  /** Override elapsed milliseconds if not derivable from the summary. */
  elapsedMs?: number;
}

export function buildPrComment(summary: SummaryData, opts: PrCommentOptions = {}): string {
  const repoName = opts.repoName ?? summary.repoName ?? "(unknown repo)";
  const topN = opts.topN ?? 10;

  const verdictLine = renderVerdictCounts(summary);
  const costLine = renderCostLine(summary, opts.elapsedMs);
  const findingsTable = renderFindingsTable(summary.actionableFindings ?? [], topN);

  const headerSuffix = opts.runUrl ? ` · [run](${opts.runUrl})` : "";

  return [
    `### 🔐 Kuzushi scan · \`${repoName}\`${headerSuffix}`,
    "",
    verdictLine,
    "",
    costLine,
    "",
    findingsTable,
    "",
    `<sub>Generated by [Kuzushi](https://github.com/allsmog/Kuzushi). Findings truncated to top ${topN}.</sub>`,
    "",
  ].join("\n");
}

function renderVerdictCounts(summary: SummaryData): string {
  const cells: Array<[string, number]> = [];
  for (const [k, v] of Object.entries(summary.verdictCounts ?? {})) {
    if (v > 0) cells.push([k, v]);
  }
  if (cells.length === 0) return "**No findings triaged.**";
  const parts = cells.map(([k, v]) => `**${v}** ${k}`).join(" · ");
  const exploitable = summary.exploitable > 0 ? ` · 🔓 **${summary.exploitable} exploitable**` : "";
  return `${parts}${exploitable}`;
}

function renderCostLine(summary: SummaryData, overrideElapsedMs?: number): string {
  const parts: string[] = [];
  const totalCost =
    (summary.triageCostUsd ?? 0) +
    (summary.verificationCostUsd ?? 0) +
    (summary.pocHarnessCostUsd ?? 0) +
    (summary.variantAnalysisCostUsd ?? 0);
  parts.push(`💸 **$${totalCost.toFixed(2)}** total`);
  if (overrideElapsedMs != null) {
    parts.push(`⏱ ${formatDuration(overrideElapsedMs)}`);
  }
  if (summary.pocGenerated > 0) parts.push(`🧪 ${summary.pocGenerated} PoCs`);
  if (summary.variantFindings > 0) parts.push(`🧬 ${summary.variantFindings} variants`);
  return parts.join(" · ");
}

function renderFindingsTable(findings: ReadonlyArray<ActionableFinding>, topN: number): string {
  const tp = findings.filter((f) => f.verdict === "tp");
  if (tp.length === 0) return "_No true-positive findings._";
  const rows = [...tp].sort(compareSeverity).slice(0, topN);
  const header = "| # | Severity | Title | Location |";
  const divider = "|---|----------|-------|----------|";
  const body = rows
    .map((f, i) => {
      const sev = severityBadge(f);
      const title = escapeMd(f.title ?? f.ruleId ?? "(untitled)");
      const loc = `\`${f.filePath ?? "?"}:${f.startLine ?? "?"}\``;
      return `| F-${String(i + 1).padStart(4, "0")} | ${sev} | ${title} | ${loc} |`;
    })
    .join("\n");
  return [header, divider, body].join("\n");
}

function severityBadge(f: ActionableFinding): string {
  const sev = (f.displaySeverity ?? f.severity ?? "").toLowerCase();
  if (sev.includes("crit")) return "🟥 CRIT";
  if (sev.includes("high")) return "🟧 HIGH";
  if (sev.includes("med")) return "🟨 MED";
  return "⬜ LOW";
}

function compareSeverity(a: ActionableFinding, b: ActionableFinding): number {
  const order = ["critical", "high", "medium", "low"];
  const da = order.indexOf((a.displaySeverity ?? a.severity ?? "").toLowerCase());
  const db = order.indexOf((b.displaySeverity ?? b.severity ?? "").toLowerCase());
  if (da === db) return (a.fingerprint ?? "").localeCompare(b.fingerprint ?? "");
  return (da < 0 ? 99 : da) - (db < 0 ? 99 : db);
}

function formatDuration(ms: number): string {
  const secs = Math.max(0, Math.floor(ms / 1000));
  if (secs < 60) return `${secs}s`;
  const m = Math.floor(secs / 60);
  const s = secs % 60;
  return s === 0 ? `${m}m` : `${m}m ${s}s`;
}

function escapeMd(s: string): string {
  return s.replace(/\|/g, "\\|").replace(/\n/g, " ");
}
