/**
 * GitHub integration worker — creates fix PRs and posts findings comments.
 *
 * Subscribes to:
 * - patch:complete → creates a fix PR from the patch worktree
 * - report:complete → posts findings summary as a PR comment or issue
 */

import { execFileSync } from "node:child_process";
import type { MessageBus } from "../types.js";
import type { PatchCompleteEvent, ReportCompleteEvent } from "../events.js";
import type { KuzushiConfig } from "../../types.js";
import { getLogger } from "../../logger.js";
import { toErrorMessage } from "../../utils.js";

const log = getLogger("github");

export interface GitHubWorkerDeps {
  config: KuzushiConfig;
}

export function registerGitHubWorker(
  bus: MessageBus,
  deps: GitHubWorkerDeps,
): void {
  const githubConfig = resolveGitHubConfig(deps.config);
  if (!githubConfig.enabled) return;

  if (githubConfig.createFixPrs) {
    bus.subscribe<PatchCompleteEvent>("patch:complete", async (event) => {
      const { context, fingerprint, status, worktreePath, costUsd } = event.payload;
      if (status !== "SOUND" || !worktreePath) return;

      try {
        const branchName = `kuzushi/fix-${fingerprint.slice(0, 12)}`;
        const repoRoot = context.repoRoot;

        // Create branch from worktree changes
        execGit(["checkout", "-b", branchName], worktreePath);
        execGit(["add", "-A"], worktreePath);
        execGit(
          ["commit", "-m", `fix: patch security vulnerability ${fingerprint.slice(0, 12)}\n\nGenerated by Kuzushi security scanner.\nFinding: ${fingerprint}\nCost: $${costUsd.toFixed(4)}`],
          worktreePath,
        );
        execGit(["push", "-u", "origin", branchName], worktreePath);

        // Create PR via gh CLI
        const prBody = [
          "## Security Fix",
          "",
          `**Finding:** \`${fingerprint}\``,
          `**Status:** Verified exploitable, patch validated`,
          `**Patch cost:** $${costUsd.toFixed(4)}`,
          "",
          "This PR was automatically generated by [Kuzushi](https://github.com/allsmog/Kuzushi) security scanner.",
          "The vulnerability was detected, verified as exploitable, and a fix was synthesized and validated.",
        ].join("\n");

        const prUrl = execGh(
          ["pr", "create",
            "--title", `fix: security patch for ${fingerprint.slice(0, 12)}`,
            "--body", prBody,
            "--base", getDefaultBranch(repoRoot),
            "--head", branchName,
          ],
          repoRoot,
        );

        log.info(`Created fix PR: ${prUrl.trim()}`);
      } catch (error) {
        log.error(`Failed to create fix PR for ${fingerprint}: ${toErrorMessage(error)}`);
      }
    });
  }

  if (githubConfig.postFindingsComment) {
    bus.subscribe<ReportCompleteEvent>("report:complete", async (event) => {
      const { context } = event.payload;

      try {
        // Check if we're on a PR branch
        const currentBranch = execGit(["rev-parse", "--abbrev-ref", "HEAD"], context.repoRoot).trim();
        const defaultBranch = getDefaultBranch(context.repoRoot);

        if (currentBranch === defaultBranch) {
          log.info("On default branch — skipping PR comment (no open PR)");
          return;
        }

        // Find open PR for this branch
        const prNumber = execGh(
          ["pr", "view", "--json", "number", "--jq", ".number"],
          context.repoRoot,
        ).trim();

        if (!prNumber) {
          log.info("No open PR found for current branch — skipping comment");
          return;
        }

        // Post comment with scan summary
        const comment = [
          "## 🔍 Kuzushi Security Scan Results",
          "",
          `Scan completed on \`${context.repoName}\`.`,
          "",
          "See the full report in the scan artifacts.",
          "",
          "_Generated by [Kuzushi](https://github.com/allsmog/Kuzushi) security scanner._",
        ].join("\n");

        execGh(
          ["pr", "comment", prNumber, "--body", comment],
          context.repoRoot,
        );

        log.info(`Posted findings comment on PR #${prNumber}`);
      } catch (error) {
        log.error(`Failed to post findings comment: ${toErrorMessage(error)}`);
      }
    });
  }
}

interface GitHubIntegrationConfig {
  enabled: boolean;
  createFixPrs: boolean;
  postFindingsComment: boolean;
}

function resolveGitHubConfig(config: KuzushiConfig): GitHubIntegrationConfig {
  const raw = (config as unknown as Record<string, unknown>)["github"];
  if (!raw || typeof raw !== "object") {
    return {
      enabled: Boolean((config as unknown as Record<string, unknown>)["githubPr"] || (config as unknown as Record<string, unknown>)["githubComment"]),
      createFixPrs: Boolean((config as unknown as Record<string, unknown>)["githubPr"]),
      postFindingsComment: Boolean((config as unknown as Record<string, unknown>)["githubComment"]),
    };
  }

  const gh = raw as Record<string, unknown>;
  return {
    enabled: true,
    createFixPrs: gh["createFixPrs"] !== false,
    postFindingsComment: gh["postFindingsComment"] !== false,
  };
}

function execGit(args: string[], cwd: string): string {
  return execFileSync("git", args, {
    cwd,
    encoding: "utf-8",
    timeout: 30_000,
    stdio: ["pipe", "pipe", "pipe"],
  });
}

function execGh(args: string[], cwd: string): string {
  return execFileSync("gh", args, {
    cwd,
    encoding: "utf-8",
    timeout: 30_000,
    stdio: ["pipe", "pipe", "pipe"],
  });
}

function getDefaultBranch(repoRoot: string): string {
  try {
    const remote = execGit(["remote", "show", "origin"], repoRoot);
    const match = remote.match(/HEAD branch:\s*(\S+)/);
    return match?.[1] ?? "main";
  } catch {
    return "main";
  }
}
