    #[test]
    fn renders_all_eight_headings_in_contract_order() {
        let markdown = render_schema_markdown(&sample_document(), "acme-backup", "/repo");
        let expected = [
            "# Threat Model: acme-backup",
            "## 1. System context",
            "## 2. Assets",
            "## 3. Entry points & trust boundaries",
            "## 4. Threats",
            "## 5. Deprioritized",
            "## 6. Open questions",
            "## 7. Provenance",
            "## 8. Recommended mitigations",
        ];
        let mut cursor = 0;
        for heading in expected {
            let position = markdown[cursor..]
                .find(&format!("{heading}\n"))
                .unwrap_or_else(|| panic!("missing or out-of-order heading: {heading}"));
            cursor += position;
        }
    }

    #[test]
    fn threat_table_uses_exact_columns_display_id_and_contract_values() {
        let markdown = render_schema_markdown(&sample_document(), "acme-backup", "/repo");
        assert!(markdown.contains(
            "| id | threat | actor | surface | asset | impact | likelihood | status | controls | evidence |"
        ));
        assert!(markdown.contains(
            "| T1 | RCE via untrusted archive parsing | remote_unauth | handle_upload | customer backups | critical | likely | unmitigated | none | CVE-2026-1234, fp_deadbeef |"
        ));
    }

    #[test]
    fn mitigation_rows_map_model_threat_ids_to_display_ids() {
        let markdown = render_schema_markdown(&sample_document(), "acme-backup", "/repo");
        assert!(markdown.contains("| sandbox the decoder process | T1 | yes | M |"));
    }

    #[test]
    fn provenance_renders_mode_date_and_revisioned_target() {
        let markdown = render_schema_markdown(&sample_document(), "acme-backup", "/repo");
        assert!(markdown.contains("- mode: staged"));
        assert!(markdown.contains("- date: 2025-07-22"));
        assert!(markdown.contains("- target: /repo @ 436b943f"));
        assert!(markdown.contains("- inputs: context, threat-model"));
        assert!(markdown.contains("- owner: unset"));
    }

    #[test]
    fn empty_document_renders_headings_with_empty_tables() {
        let markdown = render_schema_markdown(&json!({}), "bare", "/repo");
        assert!(markdown.contains("## 4. Threats"));
        assert!(markdown.contains("## 8. Recommended mitigations"));
        assert!(markdown.contains("| asset | description | sensitivity |"));
        assert!(markdown.contains("| threat | reason |"));
        assert!(!markdown.contains("| T1 |"));
    }

    #[test]
    fn table_cells_escape_pipes_and_newlines() {
        let document = json!({"threats": [{
            "displayId": "T1",
            "title": "a|b\nc",
            "impact": "low",
            "likelihood": "rare",
            "status": "unmitigated"
        }]});
        let markdown = render_schema_markdown(&document, "x", "/repo");
        assert!(markdown.contains("| T1 | a\\|b c |"));
    }
