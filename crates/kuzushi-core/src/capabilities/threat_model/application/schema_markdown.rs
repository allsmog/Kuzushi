use super::*;

/// Render the finished ThreatModelDocument as a harness-contract
/// `THREAT_MODEL.md`: eight exact section headings in order, the exact table
/// column orders, and the closed enum vocabulary — downstream tooling parses
/// this file with regex. Sections with no backing data render the heading and
/// an empty table; nothing is invented.
pub fn render_schema_markdown(document: &Value, system_name: &str, target: &str) -> String {
    let sections = [
        format!("# Threat Model: {system_name}"),
        system_context_section(document, system_name),
        assets_section(document),
        entry_points_section(document),
        threats_section(document),
        deprioritized_section(document),
        open_questions_section(document),
        provenance_section(document, target),
        recommended_mitigations_section(document),
    ];
    format!("{}\n", sections.join("\n\n"))
}

fn system_context_section(document: &Value, system_name: &str) -> String {
    let prose = ["systemContext", "system_context", "context", "description"]
        .iter()
        .find_map(|key| document.get(*key).and_then(Value::as_str))
        .map(str::to_string)
        .unwrap_or_else(|| generated_context_line(document, system_name));
    format!("## 1. System context\n\n{prose}")
}

/// When the model emitted no context prose, describe the document itself —
/// counts and methodology are facts about this build, not invented
/// architecture.
fn generated_context_line(document: &Value, system_name: &str) -> String {
    let count = |pointer: &str| array_len(document.pointer(pointer));
    format!(
        "Threat model for {system_name}, generated by kuzushi ({} methodology): \
         {} components, {} data flows, {} trust boundaries, {} threats.",
        document
            .get("methodology")
            .and_then(Value::as_str)
            .unwrap_or("stride"),
        count("/dfd/nodes"),
        count("/dfd/flows"),
        count("/dfd/trustBoundaries"),
        count("/threats"),
    )
}

fn assets_section(document: &Value) -> String {
    let rows = array_rows(document, "assets")
        .iter()
        .map(|row| {
            table_row(&[
                object_str(row, &["asset"]),
                object_str(row, &["description"]),
                object_str(row, &["sensitivity"]),
            ])
        })
        .collect::<Vec<_>>();
    section_with_table(
        "## 2. Assets",
        "| asset | description | sensitivity |",
        3,
        rows,
    )
}

fn entry_points_section(document: &Value) -> String {
    let entry_points = document
        .pointer("/attackSurface/entryPoints")
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default();
    let rows = entry_points
        .iter()
        .map(|row| {
            table_row(&[
                object_str(row, &["name", "entryPoint", "entry_point"]),
                object_str(row, &["description"]),
                object_str(row, &["trustZone", "trustBoundary", "trust_boundary"]),
                object_str(row, &["reachableAssets", "reachable_assets"]),
            ])
        })
        .collect::<Vec<_>>();
    section_with_table(
        "## 3. Entry points & trust boundaries",
        "| entry_point | description | trust_boundary | reachable_assets |",
        4,
        rows,
    )
}

fn threats_section(document: &Value) -> String {
    let rows = array_rows(document, "threats")
        .iter()
        .map(|threat| threat_row(threat))
        .collect::<Vec<_>>();
    section_with_table(
        "## 4. Threats",
        "| id | threat | actor | surface | asset | impact | likelihood | status | controls | evidence |",
        10,
        rows,
    )
}

fn threat_row(threat: &Value) -> String {
    table_row(&[
        object_str(threat, &["displayId", "stableId", "id"]),
        object_str(threat, &["title", "description"]),
        object_str(threat, &["actor"]),
        object_str(threat, &["surface"]),
        object_str(threat, &["asset"]),
        object_str(threat, &["impact"]),
        object_str(threat, &["likelihood"]),
        object_str(threat, &["status"]),
        threat_controls(threat),
        threat_evidence(threat),
    ])
}

/// Per the schema: current mitigations, or the literal `none`.
fn threat_controls(threat: &Value) -> String {
    let controls = threat
        .get("existingMitigations")
        .and_then(Value::as_array)
        .map(|items| {
            items
                .iter()
                .filter_map(Value::as_str)
                .collect::<Vec<_>>()
                .join("; ")
        })
        .unwrap_or_default();
    if controls.is_empty() {
        "none".to_string()
    } else {
        controls
    }
}

fn threat_evidence(threat: &Value) -> String {
    threat
        .get("evidence")
        .and_then(Value::as_array)
        .map(|items| {
            items
                .iter()
                .filter_map(evidence_ref)
                .collect::<Vec<_>>()
                .join(", ")
        })
        .unwrap_or_default()
}

fn evidence_ref(entry: &Value) -> Option<String> {
    match entry {
        Value::String(reference) => Some(reference.clone()),
        Value::Object(fields) => fields
            .get("ref")
            .and_then(Value::as_str)
            .map(str::to_string),
        _ => None,
    }
}

fn deprioritized_section(document: &Value) -> String {
    let rows = array_rows(document, "deprioritized")
        .iter()
        .map(|row| {
            table_row(&[
                object_str(
                    row,
                    &["threat", "title", "entryPoint", "entry_point", "boundary"],
                ),
                object_str(row, &["reason"]),
            ])
        })
        .collect::<Vec<_>>();
    section_with_table("## 5. Deprioritized", "| threat | reason |", 2, rows)
}

fn open_questions_section(document: &Value) -> String {
    let questions = array_rows(document, "openQuestions")
        .iter()
        .filter_map(open_question_text)
        .map(|question| format!("- {question}"))
        .collect::<Vec<_>>();
    if questions.is_empty() {
        "## 6. Open questions".to_string()
    } else {
        format!("## 6. Open questions\n\n{}", questions.join("\n"))
    }
}

fn open_question_text(entry: &Value) -> Option<String> {
    if let Some(question) = entry.as_str() {
        return Some(question.into());
    }
    let question = object_str(entry, &["question", "text"]);
    if question.is_empty() {
        return None;
    }
    let answer = object_str(entry, &["answer"]);
    Some(question_with_answer(question, answer))
}

fn question_with_answer(question: String, answer: String) -> String {
    if answer.is_empty() {
        return question;
    }
    format!("{question}\n  Answer: {answer}")
}

fn provenance_section(document: &Value, target: &str) -> String {
    let provenance = document
        .get("provenance")
        .cloned()
        .unwrap_or_else(|| json!({}));
    let mode = provenance
        .get("pipeline")
        .and_then(Value::as_str)
        .unwrap_or("unknown");
    let date = provenance
        .get("builtAtMs")
        .and_then(Value::as_u64)
        .map(civil_date_from_epoch_ms)
        .unwrap_or_else(|| "unknown".to_string());
    format!(
        "## 7. Provenance\n\n- mode: {mode}\n- date: {date}\n- target: {}\n- inputs: {}\n- owner: unset",
        provenance_target(&provenance, target),
        provenance_inputs(&provenance),
    )
}

fn provenance_target(provenance: &Value, target: &str) -> String {
    match provenance.get("revision").and_then(Value::as_str) {
        Some(revision) => {
            let dirty = provenance
                .get("revisionDirty")
                .and_then(Value::as_bool)
                .unwrap_or(false);
            let suffix = if dirty { "+dirty" } else { "" };
            format!("{target} @ {revision}{suffix}")
        }
        None => target.to_string(),
    }
}

/// Prefer the system-attested `sources` record; fall back to the legacy
/// model-authored `sourceLabels` so documents persisted before source
/// provenance became system-owned still render.
fn provenance_inputs(provenance: &Value) -> String {
    if let Some(labels) = system_source_labels(provenance) {
        return labels;
    }
    let labels = provenance
        .get("sourceLabels")
        .and_then(Value::as_array)
        .map(|items| {
            items
                .iter()
                .filter_map(Value::as_str)
                .collect::<Vec<_>>()
                .join(", ")
        })
        .unwrap_or_default();
    if labels.is_empty() {
        "none".to_string()
    } else {
        labels
    }
}

fn system_source_labels(provenance: &Value) -> Option<String> {
    let rows = provenance.get("sources")?.as_array()?;
    let labels = rows
        .iter()
        .filter_map(source_row_label)
        .collect::<Vec<_>>()
        .join(", ");
    (!labels.is_empty()).then_some(labels)
}

fn source_row_label(row: &Value) -> Option<String> {
    let label = row.get("label")?.as_str()?;
    match row.get("status").and_then(Value::as_str) {
        Some("loaded") => Some(label.to_string()),
        Some(status) => Some(format!("{label} ({status})")),
        None => Some(label.to_string()),
    }
}

fn recommended_mitigations_section(document: &Value) -> String {
    let display_ids = threat_display_id_map(document);
    let rows = array_rows(document, "recommendedMitigations")
        .iter()
        .map(|row| mitigation_table_row(row, &display_ids))
        .collect::<Vec<_>>();
    section_with_table(
        "## 8. Recommended mitigations",
        "| mitigation | threat_ids | closes_class | effort |",
        4,
        rows,
    )
}

fn mitigation_table_row(row: &Value, display_ids: &BTreeMap<String, String>) -> String {
    let ids = row
        .get("threatIds")
        .and_then(Value::as_array)
        .map(|items| {
            items
                .iter()
                .filter_map(Value::as_str)
                .map(|id| {
                    display_ids
                        .get(id)
                        .cloned()
                        .unwrap_or_else(|| id.to_string())
                })
                .collect::<Vec<_>>()
                .join(",")
        })
        .unwrap_or_default();
    table_row(&[
        object_str(row, &["mitigation"]),
        ids,
        object_str(row, &["closesClass"]),
        object_str(row, &["effort"]),
    ])
}

/// Mitigation rows may cite model-emitted threat ids or stableIds; render
/// them as the persisted display ids when the reference resolves.
fn threat_display_id_map(document: &Value) -> BTreeMap<String, String> {
    let mut map = BTreeMap::new();
    for threat in array_rows(document, "threats") {
        let Some(display_id) = threat.get("displayId").and_then(Value::as_str) else {
            continue;
        };
        for key in ["id", "stableId", "displayId"] {
            if let Some(reference) = threat.get(key).and_then(Value::as_str) {
                map.insert(reference.to_string(), display_id.to_string());
            }
        }
    }
    map
}

fn array_rows(document: &Value, key: &str) -> Vec<Value> {
    document
        .get(key)
        .and_then(Value::as_array)
        .cloned()
        .unwrap_or_default()
}

fn object_str(value: &Value, keys: &[&str]) -> String {
    keys.iter()
        .find_map(|key| value.get(*key).and_then(Value::as_str))
        .unwrap_or("")
        .to_string()
}

fn section_with_table(heading: &str, header: &str, columns: usize, rows: Vec<String>) -> String {
    let separator = format!("|{}", "---|".repeat(columns));
    let mut lines = vec![
        heading.to_string(),
        String::new(),
        header.to_string(),
        separator,
    ];
    lines.extend(rows);
    lines.join("\n")
}

fn table_row(cells: &[String]) -> String {
    let escaped = cells
        .iter()
        .map(|cell| escape_table_cell(cell))
        .collect::<Vec<_>>();
    format!("| {} |", escaped.join(" | "))
}

fn escape_table_cell(cell: &str) -> String {
    cell.replace('\n', " ").replace('|', "\\|")
}

/// YYYY-MM-DD from epoch milliseconds (UTC), via the standard civil-from-days
/// algorithm — provenance needs a date, not a datetime dependency.
fn civil_date_from_epoch_ms(ms: u64) -> String {
    let days = (ms / 86_400_000) as i64;
    let (year, month, day) = civil_from_days(days);
    format!("{year:04}-{month:02}-{day:02}")
}

fn civil_from_days(days_from_epoch: i64) -> (i64, u32, u32) {
    let z = days_from_epoch + 719_468;
    let era = if z >= 0 { z } else { z - 146_096 } / 146_097;
    let day_of_era = (z - era * 146_097) as u64;
    let year_of_era =
        (day_of_era - day_of_era / 1_460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
    let year = year_of_era as i64 + era * 400;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let month_index = (5 * day_of_year + 2) / 153;
    let day = (day_of_year - (153 * month_index + 2) / 5 + 1) as u32;
    let month = if month_index < 10 {
        month_index + 3
    } else {
        month_index - 9
    } as u32;
    (if month <= 2 { year + 1 } else { year }, month, day)
}

