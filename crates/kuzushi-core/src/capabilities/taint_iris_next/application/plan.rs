use super::*;

pub(crate) fn build_taint_iris_next_plan(
    target: &Path,
    options: TaintIrisNextInput,
) -> Result<TaintIrisNextPlan> {
    let repo_root = target.to_path_buf();
    // E2a: when the operator supplies `targetSubdir`, scope all of
    // structural collection, the discovery sweep, the
    // identifier-injection detector, and joern flow query to that
    // subtree. `repo_root` stays at the original --target so the
    // codeql DB (which lives at <repo_root>/.kuzushi/codeql-db by
    // convention) is still found, and threat-model / context
    // artifacts under <repo_root>/.kuzushi/ still load.
    let scan_root = match options.target_subdir.as_deref() {
        Some(subdir) => {
            let joined = repo_root.join(subdir);
            // Reject any path that escapes the repo via `..`. The
            // input parser also rejects '..' segments, but defense
            // in depth: re-check against the canonicalised parent.
            let canonical_root =
                std::fs::canonicalize(&repo_root).unwrap_or_else(|_| repo_root.clone());
            let canonical_joined =
                std::fs::canonicalize(&joined).unwrap_or_else(|_| joined.clone());
            if !canonical_joined.starts_with(&canonical_root) {
                anyhow::bail!("taint-iris-next:hunt targetSubdir escapes --target: {subdir:?}");
            }
            joined
        }
        None => repo_root.clone(),
    };
    let context = load_taint_iris_next_context(&repo_root);
    let threat_model = load_taint_iris_next_threat_model(&repo_root);
    let mut languages = options.languages.clone();
    languages.extend(taint_iris_next_context_languages(context.value.as_ref()));
    languages.extend(detect_taint_iris_next_languages(target)?);
    languages = languages
        .into_iter()
        .map(|language| normalize_taint_next_language(&language))
        .filter(|language| !language.is_empty())
        .collect::<BTreeSet<_>>()
        .into_iter()
        .collect();

    let threat_cwes = collect_taint_iris_next_cwes(threat_model.value.as_ref());
    let attack_surface_hints =
        collect_taint_iris_next_attack_surface_hints(threat_model.value.as_ref());
    let context_keywords = taint_iris_next_context_keywords(context.value.as_ref(), target)?;
    // Prefer a target-specific catalog generated by `taint-iris-next:catalog`
    // when one exists at <target>/.kuzushi/taint-iris-next-catalog.json.
    // Falling back to the static built-in catalog keeps the hunt usable on
    // targets that haven't run catalog generation yet.
    let mut ranked = match load_taint_iris_next_target_catalog(&repo_root) {
        Some(custom) => {
            let mut entries = custom;
            entries.sort_by(|a, b| b.score.cmp(&a.score));
            entries
        }
        None => rank_taint_iris_next_catalog(&languages, &threat_cwes, &context_keywords)
            .into_iter()
            .collect::<Vec<_>>(),
    };
    if !options.extra_catalog_entries.is_empty() {
        ranked = merge_taint_iris_next_extra_entries(ranked, &options.extra_catalog_entries);
    }
    let catalog = ranked
        .into_iter()
        .take(options.caps.max_catalog_entries)
        .collect::<Vec<_>>();
    // Apply the operator's cweFocus shell-option filter. When the
    // allow-list is non-empty, drop catalog entries whose CWE isn't in
    // it so the structural seeds + agent prompt stay scoped to the
    // requested classes (e.g. CWE-78 / CWE-94 / CWE-426 for a privesc +
    // RCE hunt). Empty allow-list = keep everything.
    let catalog = if options.cwe_focus.is_empty() {
        catalog
    } else {
        let allow: std::collections::BTreeSet<String> = options
            .cwe_focus
            .iter()
            .map(|cwe| cwe.to_ascii_uppercase())
            .collect();
        catalog
            .into_iter()
            .filter(|entry| allow.contains(&entry.cwe.to_ascii_uppercase()))
            .collect()
    };
    // Discovery pass: regex-scan the actual source files for
    // language-specific entry-point markers + canonical privesc/RCE
    // sinks. We always run it (cheap, pure-Rust) but the operator can
    // opt out via the `discoverSignals` shell option (env var
    // KUZUSHI_DISCOVER_SIGNALS=0). The result is folded into the
    // ranking pass below and surfaced into the agent prompt; it does
    // NOT replace the catalog, just supplements it.
    // Lift the catalog's per-entry `regex_markers` (C2/C3) into the
    // discovery sweep. Codebase-shape markers (pgcrypto's `pullf_*`,
    // libxml2's `xmlParse*`, ...) travel via the LLM-built catalog
    // rather than via a code change to the static `MARKERS` table.
    let catalog_markers = catalog_regex_markers_for_discovery(&catalog);
    let discovered_signals =
        run_taint_iris_next_discovery_for_plan(&repo_root, &options, &catalog_markers);
    persist_taint_iris_next_discovered_signals(&repo_root, &discovered_signals);

    // Re-rank (or re-filter) the catalog using discovered signals as a
    // tiebreaker: entries whose source or sink names overlap with
    // primitives we observed in the code score higher.
    let catalog = boost_catalog_with_discovered_signals(catalog, &discovered_signals);
    // Threat-model attack-surface hints stack on top of discovery: an
    // entry-point named in the threat model AND observed in code is
    // the strongest signal we have. The bonus is smaller than the
    // CWE-match bonus (+100) so threat-model CWE matches still win
    // ordering, but we make sure the attack-surface contribution can
    // tip a tied entry.
    let catalog = boost_catalog_with_attack_surface_hints(catalog, &attack_surface_hints);
    // Phantom-entry fallback: when the operator's `cwe_focus` includes
    // CWEs the post-boost catalog has no entries for, synthesise a
    // phantom entry per missing CWE whose source/sink signals come
    // from (1) threat-model `attackSurface` when present, falling back
    // to (2) the static-marker discovery sweep's per-CWE primitives
    // (e.g. dlopen / load_external_function for CWE-94, system / popen
    // for CWE-78). This keeps the agent's `selectedCwes` validator from
    // rejecting an honest claim like "I see CWE-94 candidates from
    // discovery" when the static catalog ships no CWE-94 entry for
    // this language. Both fallbacks are framework-agnostic.
    let catalog = supplement_catalog_with_phantom_focus_entries(
        catalog,
        &attack_surface_hints,
        &discovered_signals,
        &options.cwe_focus,
    );
    let structural_queries = build_taint_iris_next_structural_queries(&catalog);
    let prompt_catalog = render_taint_iris_next_catalog(&catalog);
    let mut backend = choose_taint_iris_next_backend(&options.backend, &repo_root);
    // E2b: if the operator pointed at the whole postgres tree
    // without targetSubdir AND the tree is large enough that joern
    // is likely to hang on broad CWE regexes (1612 .c files etc),
    // surface a partition recommendation as a backend warning.
    // Doesn't change behavior — the hunt still proceeds — but
    // operators see actionable next steps in `kuzushi findings` /
    // run output.
    if options.target_subdir.is_none() {
        let c_file_count = count_c_files_under(&repo_root);
        if should_recommend_partitioning(&repo_root, c_file_count) {
            let parts = postgres_partitions_for(&repo_root);
            backend.warnings.push(format!(
                "target looks postgres-shaped with {c_file_count} .c files; broad CWE regex on joern \
                 will likely hang. Run partitioned hunts in parallel with `targetSubdir` for each \
                 subdir: {}",
                parts
                    .iter()
                    .take(8)
                    .map(|p| p.display().to_string())
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
    }

    Ok(TaintIrisNextPlan {
        target: target.to_path_buf(),
        scan_root,
        repo_root,
        mode: options.mode,
        caps: options.caps,
        languages,
        context_status: context.status,
        threat_model_status: threat_model.status,
        repo_context: context.value,
        threat_model: threat_model.value,
        catalog,
        structural_queries,
        prompt_catalog,
        backend,
        max_budget_usd: options.max_budget_usd,
        allow_deterministic_fallback: options.allow_deterministic_fallback,
        cwe_focus: options.cwe_focus,
        discovered_signals,
    })
}

/// Cheap .c-file count under a directory. Stops walking after
/// `cap` to keep the partition heuristic from O(tree) scanning a
/// 20GB monorepo just to decide whether to recommend partitioning.
/// Returns the count saturated at `cap`.
fn count_c_files_under(root: &Path) -> usize {
    const CAP: usize = 2000;
    let mut count = 0usize;
    let mut stack: Vec<PathBuf> = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        if count >= CAP {
            return count;
        }
        let Ok(entries) = std::fs::read_dir(&dir) else {
            continue;
        };
        for entry in entries.flatten() {
            if count >= CAP {
                return count;
            }
            let path = entry.path();
            let Ok(ft) = entry.file_type() else { continue };
            if ft.is_dir() {
                // Skip the `.kuzushi/` artifact dir + .git
                if let Some(name) = path.file_name().and_then(|n| n.to_str()) {
                    if name == ".kuzushi"
                        || name == ".git"
                        || name == "target"
                        || name == "node_modules"
                    {
                        continue;
                    }
                }
                stack.push(path);
            } else if ft.is_file() {
                if let Some(ext) = path.extension().and_then(|e| e.to_str()) {
                    if ext == "c" || ext == "cpp" || ext == "cc" || ext == "cxx" {
                        count += 1;
                    }
                }
            }
        }
    }
    count
}

/// Bridge between `build_taint_iris_next_plan` and the discovery
/// scanner. Reads the same source-file budget the structural pass
/// uses (so we don't slurp the entire postgres tree twice on a hunt;
/// the costs are tracked together). Bails early to an empty signal set
/// when discovery is explicitly disabled or the file walker fails.
///
/// `extra_markers` carries codebase-shape markers lifted from the
/// LLM-built catalog's `regex_markers` field. Empty when no catalog is
/// present, when the LLM emitted no markers, or when the operator is
/// running against the static-fallback catalog.
fn run_taint_iris_next_discovery_for_plan(
    repo_root: &Path,
    options: &TaintIrisNextInput,
    extra_markers: &[OwnedMarkerSpec],
) -> DiscoveredSignals {
    if !options.discover_signals {
        return DiscoveredSignals::default();
    }
    // Hard cap: the discovery sweep is regex-only so it scales linearly
    // with file count, but we don't want to blow $$$ on disk read for a
    // 100k-file repo when the structural pass has its own (smaller)
    // sample. Match the structural pass's `max_files_per_query` cap.
    let max_files = options
        .caps
        .max_files_per_query
        .saturating_mul(8)
        .max(2_000);
    let max_bytes = 256 * 1024;
    let files = match collect_taint_iris_next_source_files(repo_root, Some(max_files), max_bytes) {
        Ok(files) => files,
        Err(_) => return DiscoveredSignals::default(),
    };
    run_taint_iris_next_source_sink_discovery(&files, 16, extra_markers)
}

/// Hard cap on the total number of LLM-curated regex markers fed into a
/// single discovery sweep. Each entry in the catalog can contribute up
/// to its own marker count, but the merged stream stops at this cap.
/// Defensive guard against an LLM that emits hundreds of markers per
/// entry — discovery is O(files × markers × file_size), so an unbounded
/// merge would blow the rg-pass runtime on a postgres-scale codebase.
const CATALOG_MARKER_CAP: usize = 64;

/// Flatten the catalog's `regex_markers` into the `OwnedMarkerSpec`
/// list discovery expects. The catalog's per-entry `cwe` is propagated
/// onto each `OwnedMarkerSpec` (the payload carries no CWE of its own).
/// Iteration order follows the catalog's existing score-descending
/// ordering so the highest-scored CWE's markers land first if we hit
/// the cap.
pub(crate) fn catalog_regex_markers_for_discovery(
    catalog: &[TaintIrisNextRankedCatalogEntry],
) -> Vec<OwnedMarkerSpec> {
    let mut out = Vec::new();
    for entry in catalog {
        for marker in &entry.regex_markers {
            if out.len() >= CATALOG_MARKER_CAP {
                return out;
            }
            // Default languages: when the marker doesn't specify them,
            // inherit the entry's languages. Empty fall-back is "any C"
            // — discovery's per-marker language filter is permissive
            // when the marker list is empty? No — it requires a match.
            // Inherit the entry's full language list as the default
            // (empty-language markers would otherwise never fire).
            let languages = if marker.languages.is_empty() {
                entry.languages.clone()
            } else {
                marker.languages.clone()
            };
            out.push(OwnedMarkerSpec {
                pattern: marker.pattern.clone(),
                cwe: entry.cwe.clone(),
                kind: marker.kind.clone(),
                languages,
                marker: if marker.marker.is_empty() {
                    format!("catalog.{}", entry.cwe.to_ascii_lowercase())
                } else {
                    marker.marker.clone()
                },
            });
        }
    }
    out
}

/// Add a small score boost (+15 per overlap, capped at +60) to ranked
/// catalog entries whose source or sink names appear among the
/// discovered primitives. Discovery beats threat-model CWE matching
/// for ranking weight only when the source/sink overlap is strong;
/// the threat-model CWE bonus (+100) still wins when both fire, which
/// is the desired ordering: a CWE that the threat model called out
/// AND we have evidence of in the code is the ideal candidate.
fn boost_catalog_with_discovered_signals(
    mut catalog: Vec<TaintIrisNextRankedCatalogEntry>,
    signals: &DiscoveredSignals,
) -> Vec<TaintIrisNextRankedCatalogEntry> {
    if signals.sources.is_empty() && signals.sinks.is_empty() && signals.entry_points.is_empty() {
        return catalog;
    }
    // Per-CWE source / sink indexes from discovery, with the language
    // tag attached so we only splice into entries the discovery
    // language is in scope for. Falls back to "any" entries always.
    let mut sources_by_cwe: std::collections::BTreeMap<String, Vec<&DiscoveredSignal>> =
        std::collections::BTreeMap::new();
    let mut sinks_by_cwe: std::collections::BTreeMap<String, Vec<&DiscoveredSignal>> =
        std::collections::BTreeMap::new();
    for entry in signals.sources.iter().chain(signals.entry_points.iter()) {
        sources_by_cwe
            .entry(entry.cwe.to_ascii_uppercase())
            .or_default()
            .push(entry);
    }
    for entry in &signals.sinks {
        sinks_by_cwe
            .entry(entry.cwe.to_ascii_uppercase())
            .or_default()
            .push(entry);
    }
    // Build a flat name index for the existing +15-per-overlap bonus
    // (preserves the prior ranking semantics — the bonus only fires
    // on PRE-EXISTING catalog signals that match a discovered name,
    // never on the names we're about to splice in below).
    let mut source_name_index: std::collections::BTreeSet<String> =
        std::collections::BTreeSet::new();
    let mut sink_name_index: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
    for s in sources_by_cwe.values().flatten() {
        source_name_index.insert(s.name.clone());
    }
    for s in sinks_by_cwe.values().flatten() {
        sink_name_index.insert(s.name.clone());
    }
    // pgcrypto-shaped discoveries (mbuf_*, pullf_*, pgp_mpi_*) yield
    // ~16 unique source names per CWE; a cap of 8 alphabetically
    // truncated the parser-layer reads (`pullf_read`, `pgp_mpi_read`)
    // out of the joern source set and the heap-overflow flow that
    // hinges on them never surfaced. 24 fits the pgcrypto family
    // comfortably while still bounding postgres-scale discoveries
    // (the joern script enforces its own 200-source per-CWE cap so a
    // pathological codebase can't blow up reachableByFlows runtime).
    const SPLICE_PER_ROLE_PER_ENTRY: usize = 24;
    for entry in &mut catalog {
        // Bonus snapshot (PRE-splice) — see comment above.
        let mut bonus: i32 = 0;
        for src in &entry.source_signals {
            if source_name_index.contains(src) {
                bonus = bonus.saturating_add(15);
            }
        }
        for snk in &entry.sink_signals {
            if sink_name_index.contains(snk) {
                bonus = bonus.saturating_add(15);
            }
        }
        let bonus = bonus.min(60);
        entry.score = entry.score.saturating_add(bonus);
        // Splice discovered names of MATCHING CWE into source / sink
        // signal lists so the downstream rg engine actually scans for
        // them (otherwise the +15 bonus only fires on names already
        // in the catalog, and the rg sweep never widens beyond the
        // a-priori catalog set). Restrict to source/sink roles only
        // — never touch sanitizer_signals (Thread B's body-inlining
        // reads from sanitizer_signals and the discovery markers
        // don't carry a "sanitizer" kind today; preserves the cycle-
        // free pipeline order).
        let cwe = entry.cwe.to_ascii_uppercase();
        let language_match = |sig: &DiscoveredSignal| -> bool {
            entry.languages.is_empty()
                || entry.languages.iter().any(|lang| lang == "any")
                || entry.languages.iter().any(|lang| lang == &sig.language)
        };
        if let Some(disc_sources) = sources_by_cwe.get(&cwe) {
            // Track names already in the catalog AND names spliced so far
            // — discovery output can list a marker many times (one record
            // per call site), and counting each push against the 8-slot
            // budget would mean a single duplicated name eats multiple
            // slots and starves other discovered names from making it in.
            // Mutate the set as we push so each unique name costs one slot.
            let mut already: std::collections::BTreeSet<String> =
                entry.source_signals.iter().cloned().collect();
            let mut spliced = 0usize;
            for sig in disc_sources {
                if spliced >= SPLICE_PER_ROLE_PER_ENTRY {
                    break;
                }
                if !language_match(sig) {
                    continue;
                }
                if !already.insert(sig.name.clone()) {
                    continue;
                }
                entry.source_signals.push(sig.name.clone());
                spliced += 1;
            }
        }
        if let Some(disc_sinks) = sinks_by_cwe.get(&cwe) {
            let mut already: std::collections::BTreeSet<String> =
                entry.sink_signals.iter().cloned().collect();
            let mut spliced = 0usize;
            for sig in disc_sinks {
                if spliced >= SPLICE_PER_ROLE_PER_ENTRY {
                    break;
                }
                if !language_match(sig) {
                    continue;
                }
                if !already.insert(sig.name.clone()) {
                    continue;
                }
                entry.sink_signals.push(sig.name.clone());
                spliced += 1;
            }
        }
        // Dedup + sort-stable: preserve insertion order via dedup-by-set.
        dedup_signal_list(&mut entry.source_signals);
        dedup_signal_list(&mut entry.sink_signals);
    }
    catalog.sort_by(|a, b| b.score.cmp(&a.score));
    catalog
}

fn dedup_signal_list(list: &mut Vec<String>) {
    let mut seen = std::collections::BTreeSet::new();
    list.retain(|item| seen.insert(item.clone()));
}

/// Add a +20-per-overlap (capped at +80) boost to ranked catalog
/// entries whose source signals match the threat-model's
/// `attackSurface.entryPoints` or sink signals match its
/// `externalSinks` / `roleGates.guarded`. The bonus stacks on top of
/// the discovery boost from `boost_catalog_with_discovered_signals`,
/// and is intentionally smaller than the existing threat-model CWE
/// bonus (+100) so a CWE that the threat model called out outright
/// still ranks first.
fn boost_catalog_with_attack_surface_hints(
    mut catalog: Vec<TaintIrisNextRankedCatalogEntry>,
    hints: &TaintIrisNextAttackSurfaceHints,
) -> Vec<TaintIrisNextRankedCatalogEntry> {
    if hints.is_empty() {
        return catalog;
    }
    let source_index: std::collections::BTreeSet<String> =
        hints.entry_points.iter().cloned().collect();
    let sink_index: std::collections::BTreeSet<String> = hints
        .external_sinks
        .iter()
        .chain(hints.role_gates.iter())
        .cloned()
        .collect();
    for entry in &mut catalog {
        let mut bonus: i32 = 0;
        for src in &entry.source_signals {
            if source_index.contains(src) {
                bonus = bonus.saturating_add(20);
            }
        }
        for snk in &entry.sink_signals {
            if sink_index.contains(snk) {
                bonus = bonus.saturating_add(20);
            }
        }
        let bonus = bonus.min(80);
        entry.score = entry.score.saturating_add(bonus);
    }
    catalog.sort_by(|a, b| b.score.cmp(&a.score));
    catalog
}

/// Synthesise a phantom `TaintIrisNextRankedCatalogEntry` per CWE in
/// `cwe_focus` that the post-rank/post-boost catalog has no entry
/// for. Source/sink signals come from two complementary sources:
///
/// 1. **Threat-model `attackSurface`** (preferred when populated) —
///    `entryPoints[].name` → source signals, `externalSinks[].name`
///    + `roleGates[].guarded` → sink signals. Lets a human-curated
///    threat model surface per-target patterns (`my_handler`,
///    `do_dangerous_thing`) into the rg projection pipeline.
///
/// 2. **Discovery sweep** (fallback when no threat model exists) —
///    framework-canonical discovery markers
///    (`source_sink_discovery::MARKERS`) for the target's languages.
///    Discovered `entry_points` are projected as sources for the
///    focus CWE, and discovered `sinks` are projected when their
///    intrinsic CWE matches the focus. Without this fallback, the
///    agent's `selectedCwes` validator rejects honest claims like
///    "CWE-94 candidates exist from discovery" on codebases (e.g.
///    postgres) that ship no static CWE-94 catalog entry for C and
///    no threat-model.
///
/// The downstream `build_taint_iris_next_structural_queries` + rg
/// engine pick the phantom signals up and produce role-tagged
/// candidates without further plumbing — the catalog signals are
/// exactly the shape rg wants.
///
/// No-op when:
/// - `cwe_focus` is empty (no operator-supplied focus to backfill)
/// - every focus CWE already has at least one catalog entry
/// - both threat-model hints AND discovery are empty (nothing to
///   draw from)
fn supplement_catalog_with_phantom_focus_entries(
    mut catalog: Vec<TaintIrisNextRankedCatalogEntry>,
    hints: &TaintIrisNextAttackSurfaceHints,
    discovered: &DiscoveredSignals,
    cwe_focus: &[String],
) -> Vec<TaintIrisNextRankedCatalogEntry> {
    if cwe_focus.is_empty() {
        return catalog;
    }
    let represented: std::collections::BTreeSet<String> = catalog
        .iter()
        .map(|entry| entry.cwe.to_ascii_uppercase())
        .collect();

    let threat_model_source_signals: Vec<String> = {
        let mut out = hints.entry_points.clone();
        out.sort();
        out.dedup();
        out
    };
    let threat_model_sink_signals: Vec<String> = {
        let mut out: Vec<String> = hints
            .external_sinks
            .iter()
            .chain(hints.role_gates.iter())
            .cloned()
            .collect();
        out.sort();
        out.dedup();
        out
    };
    // Pre-compute the discovery's entry-point names (universal sources
    // for any focus CWE — see Thread A's projection rationale) and a
    // per-CWE sink-name index from the discovery output.
    //
    // Cap the entry-point list before it lands in the phantom catalog:
    // a postgres tree exposes ~5000 PG_FUNCTION_ARGS-style entry
    // points, and shipping all of them as `source_signals` would push
    // the structural query seed count from ~200 to ~4000 and turn the
    // rg pass into a many-minute walk. The first 50 alphabetically is
    // good enough — the agent prompt lists the full set separately
    // under "## Discovered Signals" so high-relevance names aren't
    // lost from the model's view, only from the rg seed pass.
    const PHANTOM_DISCOVERY_SOURCE_CAP: usize = 50;
    let discovery_entry_points: Vec<String> = {
        let mut deduped: std::collections::BTreeSet<String> = discovered
            .entry_points
            .iter()
            .map(|signal| signal.name.clone())
            .collect();
        let mut ranked: Vec<(String, i32)> = deduped
            .iter()
            .map(|name| (name.clone(), phantom_entry_point_relevance(name)))
            .collect();
        deduped.clear();
        ranked.sort_by(|a, b| b.1.cmp(&a.1).then_with(|| a.0.cmp(&b.0)));
        ranked.truncate(PHANTOM_DISCOVERY_SOURCE_CAP);
        ranked.into_iter().map(|(name, _)| name).collect()
    };
    let mut discovery_sinks_by_cwe: std::collections::BTreeMap<String, Vec<String>> =
        std::collections::BTreeMap::new();
    for signal in &discovered.sinks {
        let entry = discovery_sinks_by_cwe
            .entry(signal.cwe.to_ascii_uppercase())
            .or_default();
        entry.push(signal.name.clone());
    }
    for entry in discovery_sinks_by_cwe.values_mut() {
        entry.sort();
        entry.dedup();
    }

    for cwe in cwe_focus {
        let normalised = cwe.to_ascii_uppercase();
        if represented.contains(&normalised) {
            continue;
        }
        // Prefer threat-model when populated; fall back to discovery.
        let (source_signals, sink_signals, provenance) = if !hints.is_empty()
            && (!threat_model_source_signals.is_empty() || !threat_model_sink_signals.is_empty())
        {
            (
                threat_model_source_signals.clone(),
                threat_model_sink_signals.clone(),
                "Threat-Model Attack Surface",
            )
        } else {
            let discovery_sinks = discovery_sinks_by_cwe
                .get(&normalised)
                .cloned()
                .unwrap_or_default();
            (
                discovery_entry_points.clone(),
                discovery_sinks,
                "Discovery Sweep",
            )
        };
        if source_signals.is_empty() && sink_signals.is_empty() {
            continue;
        }
        catalog.push(TaintIrisNextRankedCatalogEntry {
            cwe: normalised.clone(),
            name: format!("{provenance} ({normalised})"),
            taint_class: phantom_taint_class_for_cwe(&normalised).to_string(),
            languages: Vec::new(),
            source_signals,
            sink_signals,
            sanitizer_signals: Vec::new(),
            structural_queries: Vec::new(),
            regex_markers: Vec::new(),
            score: 50,
            reasons: vec![format!(
                "Synthesised from {provenance}; no static catalog entry covered this focus CWE.",
            )],
        });
    }
    catalog.sort_by(|a, b| b.score.cmp(&a.score));
    catalog
}

/// Local copy of the entry-point relevance heuristic that
/// `extract_taint_iris_next_evidence::entry_point_relevance_score`
/// uses for candidate sampling. Duplicated here (rather than promoted
/// to a shared module) because both paths call it independently and
/// the table is small enough that a single shared definition isn't
/// load-bearing. Keep them aligned: privesc / file / process / admin
/// tokens score positively; selectivity-estimator suffixes score
/// negatively.
fn phantom_entry_point_relevance(name: &str) -> i32 {
    let lower = name.to_ascii_lowercase();
    let mut score: i32 = 0;
    for token in [
        "exec",
        "system",
        "shell",
        "command",
        "run_program",
        "popen",
        "spawn",
        "load_library",
        "load_file",
        "load_external",
        "load_module",
        "dlopen",
        "dlsym",
        "import",
        "read_file",
        "read_binary",
        "read_server",
        "read_text",
        "write_file",
        "stat_file",
        "ls_dir",
        "ls_log",
        "ls_wal",
        "signal_backend",
        "signal_proc",
        "kill_backend",
        "reload_conf",
        "reload_config",
        "alter_system",
        "promote",
        "terminate",
        "cancel_backend",
        "set_user",
        "setuid",
        "admin",
        "super",
        "sudo",
        "privesc",
        "set_session",
        "switch_user",
        "become",
        "upload",
        "download",
        "evaluate",
        "eval",
        "compile",
        "parse_script",
        "lo_import",
        "lo_export",
    ] {
        if lower.contains(token) {
            score = score.saturating_add(20);
        }
    }
    for negative in [
        "_joinsel", "_sel", "_cmp", "_hash", "_in", "_out", "_recv", "_send", "_eq", "_lt", "_gt",
        "_le", "_ge", "_ne",
    ] {
        if lower.ends_with(negative) {
            score = score.saturating_sub(10);
        }
    }
    score
}

/// Map CWE → catalog-aligned `taintClass` for the phantom-entry path.
/// Aligns with `taint_class_for_discovered_cwe` in
/// `extract_taint_iris_next_evidence/mod.rs`. Kept inline rather than
/// imported because the discovery and threat-model paths call it
/// independently and the mapping is small enough that one shared
/// definition isn't load-bearing.
fn phantom_taint_class_for_cwe(cwe: &str) -> &'static str {
    match cwe {
        "CWE-78" | "CWE-77" => "command-injection",
        "CWE-94" => "code-injection",
        "CWE-426" => "search-path",
        "CWE-269" | "CWE-250" => "privesc",
        "CWE-732" => "permission",
        "CWE-862" => "missing-authorization",
        "CWE-89" => "sql-injection",
        "CWE-79" => "xss",
        "CWE-22" => "path-traversal",
        "CWE-918" => "ssrf",
        "CWE-502" => "deserialization",
        _ => "threat-model",
    }
}

