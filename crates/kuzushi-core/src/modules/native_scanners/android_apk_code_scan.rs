fn materialize_semgrepignore(scan_root: &Path, input: &Value) -> Result<Option<PathBuf>> {
    let include_libraries = input
        .get("includeLibraries")
        .and_then(Value::as_bool)
        .unwrap_or(false);
    let path = scan_root.join(".semgrepignore");
    let contents = if include_libraries {
        "# android-apk:code-scan: includeLibraries=true — no exclusions applied.\n"
    } else {
        DEFAULT_SEMGREPIGNORE
    };
    fs::write(&path, contents)
        .map_err(|error| anyhow::anyhow!("could not write {}: {error}", path.display()))?;
    if include_libraries {
        Ok(None)
    } else {
        Ok(Some(path))
    }
}

fn resolve_jadx_sources(input: &Value, workspace_root: &Path) -> Result<PathBuf> {
    if let Some(raw) = input
        .get("jadxDir")
        .or_else(|| input.get("jadx_dir"))
        .and_then(Value::as_str)
    {
        let path = PathBuf::from(raw);
        if path.is_dir() {
            return Ok(path);
        }
    }
    let candidate = workspace_root
        .join("android-decompiled")
        .join("jadx")
        .join("sources");
    if !candidate.is_dir() {
        anyhow::bail!(
            "android-apk:webview-scan: missing {}. Run `android-apk:prepare` with decompiler=jadx or 'both' first.",
            candidate.display()
        );
    }
    Ok(candidate)
}

fn materialize_rules(workspace_root: &Path) -> Result<PathBuf> {
    let rules_dir = workspace_root.join(".kuzushi").join("android-rules");
    fs::create_dir_all(&rules_dir)
        .map_err(|error| anyhow::anyhow!("could not create {}: {error}", rules_dir.display()))?;
    for (name, contents) in ANDROID_RULE_FILES {
        let path = rules_dir.join(name);
        fs::write(&path, contents)
            .map_err(|error| anyhow::anyhow!("could not write {}: {error}", path.display()))?;
    }
    Ok(rules_dir)
}

fn semgrep_with_rules(input: &Value, rules_dir: &Path) -> SemgrepScanner {
    let binary = input
        .get("binary")
        .or_else(|| input.get("scannerBin"))
        .and_then(Value::as_str)
        .map(str::trim)
        .filter(|value| !value.is_empty())
        .unwrap_or("semgrep")
        .to_string();
    SemgrepScanner {
        binary,
        config: vec![rules_dir.display().to_string()],
    }
}

fn rebrand_findings(findings: &mut [Finding]) {
    for finding in findings {
        finding.tool = "android-apk".to_string();
        if !finding.rule_id.starts_with("android-apk:") {
            finding.rule_id = format!("android-apk:{}", leaf_rule_id(&finding.rule_id));
        }
    }
}

fn leaf_rule_id(raw: &str) -> &str {
    raw.rsplit('.').next().unwrap_or(raw)
}

fn emit_step(ctx: &ToolExecutionContext<'_>, kind: &str, verb: &str, message: &str) {
    if let Some(trace) = ctx.trace {
        let _ = trace.step(kind, verb, message.to_string()).emit();
    }
}

fn code_scan_output(
    outcome: &CodeScanOutcome,
    persisted: Option<GenericPersistedRun>,
) -> Value {
    let summary = format!(
        "android-apk:code-scan: {} findings under {} (rules from {})",
        outcome.findings.len(),
        outcome.scan_root.display(),
        outcome.rules_dir.display()
    );
    json!({
        "ok": true,
        "summary": summary,
        "output": summary,
        "data": {
            "scanRoot": outcome.scan_root.display().to_string(),
            "rulesDir": outcome.rules_dir.display().to_string(),
            "semgrepignorePath": outcome.ignore_path.as_ref().map(|p| p.display().to_string()),
            "rulePackFiles": ANDROID_RULE_FILES.iter().map(|(name, _)| *name).collect::<Vec<_>>(),
            "findings": outcome.findings,
            "persisted": persisted,
        },
        "warnings": [],
        "errors": [],
    })
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::tempdir;

    #[test]
    fn rule_pack_files_present() {
        assert_eq!(ANDROID_RULE_FILES.len(), 11);
        for (name, contents) in ANDROID_RULE_FILES {
            assert!(contents.contains("rules:"), "rule file {name} missing rules: header");
            assert!(contents.contains("metadata:"), "rule file {name} missing metadata");
        }
    }

    #[test]
    fn materialize_rules_writes_every_pack_file() {
        let dir = tempdir().unwrap();
        let rules_dir = materialize_rules(dir.path()).unwrap();
        for (name, _) in ANDROID_RULE_FILES {
            assert!(rules_dir.join(name).is_file(), "rule {name} not written");
        }
    }

    #[test]
    fn semgrep_with_rules_uses_path_as_single_config() {
        let dir = tempdir().unwrap();
        let scanner = semgrep_with_rules(&json!({}), dir.path());
        assert_eq!(scanner.binary, "semgrep");
        assert_eq!(scanner.config, vec![dir.path().display().to_string()]);
    }

    #[test]
    fn semgrep_with_rules_honors_binary_override() {
        let dir = tempdir().unwrap();
        let scanner = semgrep_with_rules(&json!({"binary": "/opt/semgrep"}), dir.path());
        assert_eq!(scanner.binary, "/opt/semgrep");
    }

    #[test]
    fn rebrand_findings_collapses_dot_separated_ids() {
        use crate::findings::Severity;
        let mut findings = vec![
            Finding::new_tool(
                "semgrep",
                "kuzushi.android-rules.android-md5-for-auth",
                "x.java",
                10,
                None,
                Severity::High,
                "m",
            ),
            Finding::new_tool(
                "semgrep",
                "android-apk:keep-as-is",
                "y.java",
                20,
                None,
                Severity::Low,
                "m",
            ),
            Finding::new_tool(
                "semgrep",
                "android-md5-for-auth",
                "z.java",
                30,
                None,
                Severity::Medium,
                "m",
            ),
        ];
        rebrand_findings(&mut findings);
        assert_eq!(findings[0].tool, "android-apk");
        assert_eq!(findings[0].rule_id, "android-apk:android-md5-for-auth");
        assert_eq!(findings[1].rule_id, "android-apk:keep-as-is");
        assert_eq!(findings[2].rule_id, "android-apk:android-md5-for-auth");
    }

    #[test]
    fn resolve_jadx_sources_errors_when_missing() {
        let dir = tempdir().unwrap();
        let error = resolve_jadx_sources(&json!({}), dir.path()).expect_err("missing dir rejected");
        assert!(error.to_string().contains("Run `android-apk:prepare`"));
    }

    #[test]
    fn semgrepignore_written_by_default() {
        let dir = tempdir().unwrap();
        let path = materialize_semgrepignore(dir.path(), &json!({})).unwrap();
        let path = path.expect("ignore file path returned");
        assert!(path.is_file());
        let contents = std::fs::read_to_string(&path).unwrap();
        assert!(contents.contains("com/google/android/gms/"));
        assert!(contents.contains("androidx/"));
        assert!(contents.contains("kotlin/"));
    }

    #[test]
    fn semgrepignore_emptied_when_include_libraries_set() {
        let dir = tempdir().unwrap();
        // Pre-existing ignore file from a previous run.
        std::fs::write(dir.path().join(".semgrepignore"), "com/google/android/gms/\n").unwrap();
        let path = materialize_semgrepignore(dir.path(), &json!({"includeLibraries": true})).unwrap();
        assert!(path.is_none());
        let contents = std::fs::read_to_string(dir.path().join(".semgrepignore")).unwrap();
        assert!(!contents.contains("com/google/android/gms"));
        assert!(contents.contains("includeLibraries=true"));
    }
}
