/**
 * Module docs generator — pure function, drives off CopilotModule metadata.
 */

import { describe, expect, it } from "vitest";
import { generateModuleDoc } from "../../src/modules/docs.js";
import type { CopilotModule, ModuleTool, ToolResult } from "../../src/modules/types.js";

function mkTool(name: string, extras: Partial<ModuleTool> = {}): ModuleTool {
  return {
    name,
    description: `Run ${name}`,
    inputSchema: {
      type: "object",
      properties: {
        RHOST: { type: "string", description: "Remote host" },
        RPORT: { type: "integer", description: "Remote port", default: 80 },
      },
      required: ["RHOST"],
    },
    headless: true,
    async execute(): Promise<ToolResult> {
      return { ok: true, output: "" };
    },
    ...extras,
  };
}

function mkModule(overrides: Partial<CopilotModule> = {}): CopilotModule {
  return {
    id: "demo",
    displayName: "Demo Module",
    category: "offense",
    version: "1.2.3",
    description: "Demo module for tests.\nSecond line.",
    rank: "good",
    authors: ["Alice <alice@example.com>"],
    disclosureDate: "2026-01-15",
    tools: [mkTool("demo:scan")],
    references: [{ type: "CVE", value: "CVE-2026-0001" }],
    events: { produces: ["scan:finding"], consumes: [] },
    examples: ["use demo\nset RHOST 10.0.0.1\nrun"],
    ...overrides,
  };
}

describe("generateModuleDoc", () => {
  it("renders header + description + tools table + references + examples", () => {
    const md = generateModuleDoc(mkModule());
    expect(md).toContain("# Demo Module — `demo`");
    expect(md).toContain("| Category | offense |");
    expect(md).toContain("| Version | 1.2.3 |");
    expect(md).toContain("| Rank | good |");
    expect(md).toContain("| Disclosed | 2026-01-15 |");
    expect(md).toContain("Alice");
    expect(md).toContain("## Description");
    expect(md).toContain("Demo module for tests.");
    expect(md).toContain("## Tools");
    expect(md).toContain("### `demo:scan`");
    expect(md).toContain("| Option | Type | Required | Default | Description |");
    expect(md).toContain("| RHOST | string | yes |  | Remote host |");
    expect(md).toContain("| RPORT | integer |  | 80 | Remote port |");
    expect(md).toContain("## References");
    expect(md).toContain("CVE: CVE-2026-0001");
    expect(md).toContain("## Events");
    expect(md).toContain("Produces");
    expect(md).toContain("scan:finding");
    expect(md).toContain("## Examples");
    expect(md).toContain("set RHOST 10.0.0.1");
  });

  it("omits optional sections cleanly", () => {
    const md = generateModuleDoc(
      mkModule({
        authors: undefined,
        disclosureDate: undefined,
        references: undefined,
        events: undefined,
        examples: undefined,
        notes: undefined,
      }),
    );
    expect(md).not.toContain("| Disclosed |");
    expect(md).not.toContain("| Authors |");
    expect(md).not.toContain("## References");
    expect(md).not.toContain("## Events");
    expect(md).not.toContain("## Examples");
  });

  it("renders requires preflight entries", () => {
    const md = generateModuleDoc(
      mkModule({
        requires: [
          { kind: "findings", minCount: 3 },
          { kind: "env", name: "SHODAN_KEY" },
          { kind: "session", sessionKind: "ssh" },
          { kind: "hosts" },
          { kind: "snapshot", moduleId: "context", field: "appModel" },
        ],
      }),
    );
    expect(md).toContain("## Requires (preflight)");
    expect(md).toContain("3+ findings");
    expect(md).toContain("SHODAN_KEY");
    expect(md).toContain("live session of kind `ssh`");
    expect(md).toContain("1+ hosts");
    expect(md).toContain("snapshot.`appModel`");
  });

  it("renders notes when present", () => {
    const md = generateModuleDoc(
      mkModule({
        notes: {
          stability: ["stable", "crash-safe"],
          reliability: ["reliable"],
          sideEffects: ["artifacts-on-disk"],
        },
      }),
    );
    expect(md).toContain("## Notes");
    expect(md).toContain("**Stability:** stable, crash-safe");
    expect(md).toContain("**Reliability:** reliable");
    expect(md).toContain("**Side effects:** artifacts-on-disk");
  });

  it("appends a footer when footerNote is provided", () => {
    const md = generateModuleDoc(mkModule(), { footerNote: "Generated by tests" });
    expect(md).toContain("_Generated by tests_");
  });

  it("escapes pipes in descriptions so tables stay valid", () => {
    const moduleWithPipe = mkModule({
      tools: [
        mkTool("demo:pipe", {
          inputSchema: {
            type: "object",
            properties: {
              X: { type: "string", description: "a | b pipe" },
            },
          },
        }),
      ],
    });
    const md = generateModuleDoc(moduleWithPipe);
    expect(md).toContain("a \\| b pipe");
  });

  it("is deterministic — two renders produce identical output (no timestamps)", () => {
    const a = generateModuleDoc(mkModule());
    const b = generateModuleDoc(mkModule());
    expect(a).toBe(b);
  });
});
