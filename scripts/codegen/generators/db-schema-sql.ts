/**
 * Emit a consolidated `schema.sql` by running every migration in
 * `src/migrations/` against a fresh in-memory SQLite database and
 * dumping the resulting DDL.
 *
 * The migrations remain the source of truth for how production DBs
 * evolve. This artifact is a read-only reference for:
 *
 *   - People browsing the repo who want to see the full DB shape
 *     without reading 25+ migration files.
 *   - Tools that need a static SQL file (linters, ER-diagram generators).
 *
 * Determinism: `sqlite_master` rows are queried in an explicit order
 * (tables then indexes, each sorted by name) so the output is stable
 * across runs. Auto-generated internal objects (`sqlite_*`,
 * `sqlite_autoindex_*`) are filtered out.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

import Database from "better-sqlite3";

import { allMigrations, runMigrations } from "../../../src/migrations/index.js";
import type { Generator } from "../types.js";

interface MasterRow {
  type: "table" | "index" | "view" | "trigger";
  name: string;
  tbl_name: string;
  sql: string | null;
}

const HEADER = `-- Generated by scripts/codegen — do not edit.
-- Run \`pnpm codegen\` to regenerate.
--
-- This file is the consolidated SQLite schema produced by running
-- every migration in src/migrations/ against a fresh in-memory DB.
-- It is a reference artifact only; production databases evolve
-- via the numbered migration files, not this file.

`;

const generator: Generator = {
  name: "db-schema-sql",
  description: "Consolidated SQLite schema.sql (from src/migrations/)",
  async run(outDir: string): Promise<void> {
    const dest = join(outDir, "db");
    await mkdir(dest, { recursive: true });

    const db = new Database(":memory:");
    try {
      runMigrations(db, allMigrations);

      const rows = db
        .prepare(
          `
          SELECT type, name, tbl_name, sql
          FROM sqlite_master
          WHERE sql IS NOT NULL
            AND name NOT LIKE 'sqlite_%'
          ORDER BY
            CASE type
              WHEN 'table' THEN 0
              WHEN 'view'  THEN 1
              WHEN 'index' THEN 2
              WHEN 'trigger' THEN 3
              ELSE 4
            END,
            tbl_name,
            name
        `,
        )
        .all() as MasterRow[];

      const parts: string[] = [HEADER];

      let currentTable: string | null = null;
      for (const row of rows) {
        if (row.type === "table") {
          if (currentTable !== null) parts.push("\n");
          parts.push(`-- Table: ${row.name}\n`);
          parts.push(`${row.sql};\n`);
          currentTable = row.name;
        } else if (row.type === "index") {
          parts.push(`${row.sql};\n`);
        } else if (row.type === "view" || row.type === "trigger") {
          parts.push(`\n-- ${row.type}: ${row.name}\n${row.sql};\n`);
        }
      }

      // Footer: record which migration versions are baked in.
      const applied = db
        .prepare("SELECT version, name FROM schema_version ORDER BY version")
        .all() as Array<{ version: number; name: string }>;
      parts.push("\n-- Applied migrations (at generation time):\n");
      for (const m of applied) {
        parts.push(`--   ${String(m.version).padStart(3, "0")}  ${m.name}\n`);
      }

      await writeFile(join(dest, "schema.sql"), parts.join(""), "utf8");
    } finally {
      db.close();
    }
  },
};

export default generator;
