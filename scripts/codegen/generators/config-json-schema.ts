/**
 * Emit a JSON Schema describing `KuzushiConfigSchema` so external tools
 * (IDE JSON validators, the docs site, third-party config editors) have
 * a machine-readable description of the config file format.
 *
 * The Zod schema in `src/schemas.ts` remains the source of truth —
 * this file is just a projection for non-TypeScript consumers.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";

import { z } from "zod";

import { KuzushiConfigSchema } from "../../../src/schemas.js";
import type { Generator } from "../types.js";
import { formatJson } from "../util.js";

const generator: Generator = {
  name: "config-json-schema",
  description: "JSON Schema for KuzushiConfig (from src/schemas.ts)",
  async run(outDir: string): Promise<void> {
    const dest = join(outDir, "schemas");
    await mkdir(dest, { recursive: true });

    const schema = z.toJSONSchema(KuzushiConfigSchema, {
      target: "draft-2020-12",
    });
    const withMeta = {
      $comment: "Generated by scripts/codegen — do not edit. Run `pnpm codegen` to regenerate.",
      title: "KuzushiConfig",
      ...schema,
    };

    await writeFile(join(dest, "kuzushi-config.json"), formatJson(withMeta), "utf8");
  },
};

export default generator;
