/**
 * Emit JSON Schemas for the raw LLM I/O contracts (triage, verification,
 * poc-harness). These define the exact JSON shape that agent prompts
 * expect back from the model. Exposing them as JSON Schema is useful for:
 *
 *   - Prompt authors who want to show the shape to the LLM or paste it
 *     into Claude "response_format" / tool_use `input_schema` fields.
 *   - External consumers who parse Kuzushi's raw agent outputs.
 *   - Drift detection: if the Zod schema changes, the JSON Schema
 *     changes too, and `pnpm codegen:check` catches unchecked-in drift.
 */
import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import type { ZodType } from "zod";
import { z } from "zod";

import {
  RawBatchTriageOutputSchema,
  RawBatchVerificationOutputSchema,
  RawPocHarnessOutputSchema,
  RawTriageOutputSchema,
  RawVerificationOutputSchema,
} from "../../../src/schemas.js";
import type { Generator } from "../types.js";
import { formatJson } from "../util.js";

interface Entry {
  file: string;
  title: string;
  schema: ZodType;
}

const entries: Entry[] = [
  {
    file: "raw-triage-output.json",
    title: "RawTriageOutput",
    schema: RawTriageOutputSchema,
  },
  {
    file: "raw-batch-triage-output.json",
    title: "RawBatchTriageOutput",
    schema: RawBatchTriageOutputSchema,
  },
  {
    file: "raw-verification-output.json",
    title: "RawVerificationOutput",
    schema: RawVerificationOutputSchema,
  },
  {
    file: "raw-batch-verification-output.json",
    title: "RawBatchVerificationOutput",
    schema: RawBatchVerificationOutputSchema,
  },
  {
    file: "raw-poc-harness-output.json",
    title: "RawPocHarnessOutput",
    schema: RawPocHarnessOutputSchema,
  },
];

const generator: Generator = {
  name: "llm-io-json-schemas",
  description: "JSON Schemas for raw LLM I/O contracts (triage/verify/poc)",
  async run(outDir: string): Promise<void> {
    const dest = join(outDir, "schemas", "llm-io");
    await mkdir(dest, { recursive: true });

    for (const entry of entries) {
      const schema = z.toJSONSchema(entry.schema, { target: "draft-2020-12" });
      const withMeta = {
        $comment: "Generated by scripts/codegen — do not edit. Run `pnpm codegen` to regenerate.",
        title: entry.title,
        ...schema,
      };
      await writeFile(join(dest, entry.file), formatJson(withMeta), "utf8");
    }
  },
};

export default generator;
