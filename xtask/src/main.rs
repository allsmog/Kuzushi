//! Kuzushi workspace automation.
//!
//! `cargo xtask codegen` derives the operator config JSON Schema from the Rust
//! source of truth (`kuzushi_core::V2Config` + `schemars`) and writes it to
//! `generated/schemas/kuzushi-v3-config.json`. `--check` regenerates in memory
//! and fails if the committed file is stale, so CI catches config-schema drift
//! the same way `pnpm codegen:check` did for the retired zod path — but with
//! Rust as the single source of truth.

use anyhow::{bail, Context, Result};
use std::path::{Path, PathBuf};

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().skip(1).collect();
    match args.first().map(String::as_str) {
        Some("codegen") => codegen(args.iter().any(|arg| arg == "--check")),
        Some(other) => bail!("unknown xtask command {other:?}; try `cargo xtask codegen [--check]`"),
        None => bail!("usage: cargo xtask codegen [--check]"),
    }
}

/// Relative path (from repo root) of every schema `codegen` owns.
const V3_CONFIG_SCHEMA: &str = "generated/schemas/kuzushi-v3-config.json";

fn codegen(check: bool) -> Result<()> {
    let dest = repo_root().join(V3_CONFIG_SCHEMA);
    let rendered = render_v3_config_schema()?;
    if check {
        return check_up_to_date(&dest, &rendered);
    }
    write_generated(&dest, &rendered)
}

fn check_up_to_date(dest: &Path, rendered: &str) -> Result<()> {
    let existing = std::fs::read_to_string(dest).with_context(|| {
        format!(
            "missing {}; run `cargo xtask codegen`",
            dest.display()
        )
    })?;
    if existing != rendered {
        bail!(
            "{} is stale; run `cargo xtask codegen` and commit the result",
            dest.display()
        );
    }
    println!("xtask codegen --check: {} up to date", dest.display());
    Ok(())
}

fn write_generated(dest: &Path, rendered: &str) -> Result<()> {
    if let Some(parent) = dest.parent() {
        std::fs::create_dir_all(parent)
            .with_context(|| format!("could not create {}", parent.display()))?;
    }
    std::fs::write(dest, rendered)
        .with_context(|| format!("could not write {}", dest.display()))?;
    println!("xtask codegen: wrote {}", dest.display());
    Ok(())
}

/// Render `V2Config` as a deterministic, header-stamped JSON Schema string
/// (trailing newline included) so writes and `--check` compare byte-for-byte.
fn render_v3_config_schema() -> Result<String> {
    let schema = schemars::schema_for!(kuzushi_core::V2Config);
    let mut value = serde_json::to_value(&schema).context("schema is not serialisable")?;
    let object = value
        .as_object_mut()
        .context("config schema root is not a JSON object")?;
    object.insert(
        "$comment".to_string(),
        serde_json::Value::String(
            "Generated by `cargo xtask codegen` from crates/kuzushi-core V2Config — do not edit."
                .to_string(),
        ),
    );
    object.insert(
        "title".to_string(),
        serde_json::Value::String("KuzushiV3Config".to_string()),
    );
    let mut rendered =
        serde_json::to_string_pretty(&value).context("could not render config schema")?;
    rendered.push('\n');
    Ok(rendered)
}

/// Workspace root, resolved from this crate's manifest dir so `cargo xtask`
/// works regardless of the caller's current directory.
fn repo_root() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .parent()
        .expect("xtask crate always lives one level below the repo root")
        .to_path_buf()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn render_is_deterministic() {
        // `--check` compares bytes, so the same model must render identically.
        assert_eq!(
            render_v3_config_schema().unwrap(),
            render_v3_config_schema().unwrap()
        );
    }

    #[test]
    fn schema_reflects_the_rust_config_source_of_truth() {
        let rendered = render_v3_config_schema().unwrap();
        // Fields that only exist on the Rust v3 config prove it is the source,
        // not the legacy zod KuzushiConfig.
        for needle in [
            "KuzushiV3Config",
            "AgentRuntimeSelector",
            "agent_runtime",
            "GuidedPhaseConfig",
            "worker_watchdog_timeout_ms",
        ] {
            assert!(rendered.contains(needle), "schema missing {needle:?}");
        }
    }

    #[test]
    fn committed_schema_is_up_to_date() {
        // Editing the config model without `cargo xtask codegen` fails here too,
        // not just in CI.
        let dest = repo_root().join(V3_CONFIG_SCHEMA);
        let committed = std::fs::read_to_string(&dest).unwrap();
        assert_eq!(
            committed,
            render_v3_config_schema().unwrap(),
            "run `cargo xtask codegen` and commit generated/schemas/kuzushi-v3-config.json"
        );
    }
}
